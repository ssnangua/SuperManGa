import { createI18n } from "vue-i18n";

export const locales = ["zh-CN", "zh-TW", "en", "ja", "ko"] as const;

export type Locale = (typeof locales)[number];

export function isLocale(value: string | null | undefined): value is Locale {
  return !!value && (locales as readonly string[]).includes(value);
}

function mapSystemLanguageTag(tag: string): Locale | null {
  const normalized = tag.trim().replace(/_/g, "-");
  if (!normalized) return null;
  if (isLocale(normalized)) return normalized;

  const parts = normalized.toLowerCase().split("-");
  const lang = parts[0];
  const rest = parts.slice(1);

  if (lang === "zh") {
    if (
      rest.some((p) => p === "hant" || p === "tw" || p === "hk" || p === "mo")
    )
      return "zh-TW";
    return "zh-CN";
  }
  if (lang === "ja") return "ja";
  if (lang === "ko") return "ko";
  if (lang === "en") return "en";
  return null;
}

/** Map OS / browser UI languages onto a supported locale. Unmatched tags fall back to English. */
export function detectSystemLocale(): Locale {
  const candidates: string[] = [];
  if (typeof navigator !== "undefined") {
    if (Array.isArray(navigator.languages))
      candidates.push(...navigator.languages);
    if (navigator.language) candidates.push(navigator.language);
  }
  for (const tag of candidates) {
    const mapped = mapSystemLanguageTag(tag);
    if (mapped) return mapped;
  }
  return "en";
}

